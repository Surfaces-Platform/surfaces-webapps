#!/usr/bin/env bash
# Setup auth env for local dev. Creates .env.local from scratch/secrets.
# Usage: ./scripts/setup-auth.sh [app] [--force]
#   app: surfaces-web | surfaceops-web | interfacectl-web | surfaces-dev (default: all)
#   --force: overwrite existing .env.local
# Run from repo root.
set -e

SCRATCH="scratch/secrets"

# app_dir port surface_id
APPS=(
  "apps/surfaces-web:3000:surfaces.systems"
  "apps/surfaceops-web:3001:surfaceops.ai"
  "apps/interfacectl-web:3002:interfacectl.com"
  "apps/surfaces-dev:3003:surfaces.dev"
)

read_val() {
  if [[ -f "$1" ]] && [[ -s "$1" ]]; then
    head -1 "$1" | tr -d '\n\r'
  else
    echo ""
  fi
}

setup_app() {
  local app_dir="$1"
  local port="$2"
  local surface_id="$3"
  local force="$4"
  local env_local="$app_dir/.env.local"
  local env_example="$app_dir/.env.example"

  if [[ -f "$env_local" ]] && [[ "$force" != "1" ]]; then
    echo "✓ $env_local already exists (use --force to overwrite)"
    return 0
  fi

  if [[ -f "$SCRATCH/OIDC_ISSUER.txt" ]] && [[ -f "$SCRATCH/SESSION_SECRET.txt" ]] && [[ -f "$SCRATCH/OIDC_CLIENT_ID.txt" ]]; then
    local oidc_issuer oidc_client_id oidc_client_secret session_secret
    oidc_issuer=$(read_val "$SCRATCH/OIDC_ISSUER.txt")
    session_secret=$(read_val "$SCRATCH/SESSION_SECRET.txt")
    oidc_client_id=$(read_val "$SCRATCH/OIDC_CLIENT_ID.txt")
    oidc_client_secret=$(read_val "$SCRATCH/OIDC_CLIENT_SECRET.txt")

    if [[ -n "$oidc_issuer" ]] && [[ -n "$session_secret" ]] && [[ -n "$oidc_client_id" ]]; then
      cat > "$env_local" << EOF
# Generated by scripts/setup-auth.sh from scratch/secrets
PLATFORM_SURFACE_ID=$surface_id
OIDC_ISSUER=$oidc_issuer
OIDC_CLIENT_ID=$oidc_client_id
OIDC_CLIENT_SECRET=$oidc_client_secret
OIDC_REDIRECT_URI=http://localhost:$port/auth/callback
OIDC_POST_LOGOUT_REDIRECT_URI=http://localhost:$port/
SESSION_SECRET=$session_secret
OIDC_WORKSPACE_CLAIM=https://surfaces.systems/workspace_id
OIDC_SURFACE_ACCESS_CLAIM=https://surfaces.systems/surface_access
EOF
      echo "✓ Generated $env_local"
      return 0
    fi
  fi

  if [[ -f "$env_example" ]]; then
    cp "$env_example" "$env_local"
    echo "✓ Created $env_local from .env.example (fill in values from scratch/secrets)"
    return 0
  fi

  echo "Error: $env_example not found"
  return 1
}

# Parse args
FORCE=""
TARGET=""
for arg in "$@"; do
  if [[ "$arg" == "--" ]]; then
    continue
  elif [[ "$arg" == "--force" ]]; then
    FORCE="1"
  elif [[ -n "$arg" ]] && [[ "$arg" != --* ]]; then
    TARGET="$arg"
  fi
done

if [[ -z "$TARGET" ]]; then
  for entry in "${APPS[@]}"; do
    IFS=: read -r app_dir port surface_id <<< "$entry"
    setup_app "$app_dir" "$port" "$surface_id" "$FORCE"
  done
else
  found=""
  for entry in "${APPS[@]}"; do
    IFS=: read -r app_dir port surface_id <<< "$entry"
    if [[ "$(basename "$app_dir")" == "$TARGET" ]]; then
      setup_app "$app_dir" "$port" "$surface_id" "$FORCE"
      found="1"
      break
    fi
  done
  if [[ -z "$found" ]]; then
    echo "Error: unknown app '$TARGET'. Use: surfaces-web, surfaceops-web, interfacectl-web, surfaces-dev"
    exit 1
  fi
fi
